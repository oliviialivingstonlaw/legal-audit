module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });
  if (!process.env.ANTHROPIC_API_KEY) return res.status(500).json({ error: 'API key not configured' });

  var body = req.body || {};
  if (!body.docType || !body.url || !body.company_name) {
    return res.status(400).json({ error: 'docType, url и company_name обязательны' });
  }

  var d = {
    url: body.url, inn: body.inn || '', company_name: body.company_name,
    ogrn: body.ogrn || '', address: body.address || '',
    email: body.email || '', phone: body.phone || '',
    industry: body.industry || 'other',
    industry_label: LABELS[body.industry || 'other'] || 'Услуги',
    services: body.services || ''
  };

  try {
    var response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify({
        model: 'claude-sonnet-4-6',
        max_tokens: 8000,
        messages: [{ role: 'user', content: buildPrompt(body.docType, d) }]
      })
    });

    if (!response.ok) {
      var ed = await response.json();
      return res.status(500).json({ error: (ed.error && ed.error.message) || 'API error ' + response.status });
    }

    var result = await response.json();
    var html = '';
    if (result.content && Array.isArray(result.content)) {
      for (var i = 0; i < result.content.length; i++) {
        if (result.content[i].type === 'text') html += result.content[i].text;
      }
    }

    if (!html) {
      return res.status(500).json({ error: 'Модель вернула пустой ответ. stop_reason: ' + (result.stop_reason || 'unknown') });
    }

    // Убираем markdown-обёртку если есть
    html = html.replace(/^```html\n?/i, '').replace(/\n?```$/i, '').trim();

    return res.json({
      ok: true, html, docType: body.docType,
      company_name: d.company_name, url: d.url,
      generated_at: new Date().toLocaleDateString('ru-RU')
    });

  } catch(e) {
    return res.status(500).json({ error: e.message });
  }
};
